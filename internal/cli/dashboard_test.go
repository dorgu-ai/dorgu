func TestBrowserCommand(t *testing.T) {
	tests := []struct {
		goos     string
		wantName string
		wantOK   bool
	}{
		{"darwin", "open", true},
		{"linux", "xdg-open", true},
		{"freebsd", "xdg-open", true},
		{"windows", "rundll32", true},
		{"plan9", "", false},
	}
	for _, tc := range tests {
		t.Run(tc.goos, func(t *testing.T) {
			name, args, ok := browserCommand(tc.goos, testDashboardURL)
			assert.Equal(t, tc.wantOK, ok)
			assert.Equal(t, tc.wantName, name)
			if ok {
				assert.Equal(t, testDashboardURL, args[len(args)-1])
			}
		})
	}
}

func TestOpenURLNeverRunsAShellOnTheURL(t *testing.T) {
	// The URL is passed as one argv element to a fixed program, so a URL full of
	// shell metacharacters is data. This guards the shape of browserCommand.
	_, args, ok := browserCommand("linux", "http://x/?a=1;touch /tmp/pwned&b=$(id)")
	require.True(t, ok)
	assert.Len(t, args, 1)
	assert.False(t, strings.Contains(args[0], "\n"))
}

func TestOpenURLStartsTheSystemOpenerWithTheURLAsOneArgument(t *testing.T) {
	name, _, ok := browserCommand(runtime.GOOS, "x")
	if !ok || runtime.GOOS == "windows" {
		t.Skip("no POSIX opener on this platform")
	}
	dir := t.TempDir()
	record := filepath.Join(dir, "argv")
	script := "#!/bin/sh\nprintf '%s\\n' \"$#\" \"$1\" > " + record + "\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(script), 0o700))
	t.Setenv("PATH", dir)

	url := "http://127.0.0.1:1/?token=a;b&c=$(id)"
	require.NoError(t, openURL(url))

	require.Eventually(t, func() bool {
		data, err := os.ReadFile(record)
		return err == nil && strings.Contains(string(data), "token")
	}, 5*time.Second, 20*time.Millisecond)
	data, err := os.ReadFile(record)
	require.NoError(t, err)
	assert.Equal(t, "1\n"+url+"\n", string(data), "one argument, byte for byte")
}

func TestOpenURLNamesTheMissingOpener(t *testing.T) {
	name, _, ok := browserCommand(runtime.GOOS, "x")
	if !ok {
		t.Skip("no known opener on this platform")
	}
	t.Setenv("PATH", t.TempDir())

	err := openURL(testDashboardURL)

	require.Error(t, err)
	assert.Contains(t, err.Error(), name)
}
