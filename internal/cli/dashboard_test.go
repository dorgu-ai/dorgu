func TestDashboardIsRegisteredOnTheRootCommandWithItsFlags(t *testing.T) {
	var found *cobra.Command
	for _, c := range rootCmd.Commands() {
		if c.Name() == "dashboard" {
			found = c
		}
	}
	require.NotNil(t, found, "dorgu dashboard must be a root command")
	for _, flag := range []string{"port", "no-browser", "namespace", "kubeconfig"} {
		assert.NotNil(t, found.Flags().Lookup(flag), "--%s", flag)
	}
	assert.Nil(t, found.Flags().Lookup("host"), "binding anywhere but loopback is deliberately not offered")
	assert.NotNil(t, rootCmd.PersistentFlags().Lookup("context"), "--context is inherited from the root")
}

